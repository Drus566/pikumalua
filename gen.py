import random

random.seed(42)  # для воспроизводимости

for year in range(1881, 2014):  # 2014 не включается, т.е. до 2013 включительно
    # абсолютное значение от 0 до 1 с 9 знаками
    abs_val = round(random.uniform(0.000000001, 0.999999999), 9)
    # знак: + для чётных разностей (1881, 1883, …), – для нечётных
    sign = 1 if (year - 1881) % 2 == 0 else -1
    print(f"{year},{sign * abs_val:.9f}")